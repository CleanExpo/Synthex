/**
 * lint-staged runs `prettier --write` on *.md at commit, so markdown output is
 * formatted with this repository's Prettier config here; otherwise the commit
 * hook would rewrite it and --check would report drift forever.
 */
async function formatMarkdown(rel, text) {
  const config =
    (await prettier.resolveConfig(path.join(DEFAULT_ROOT, rel))) ?? {};
  return prettier.format(text, { ...config, parser: 'markdown' });
}

export async function generate(root) {
  const errors = collectErrorCodes(root);
  const limits = collectRateLimits(root);
  return {
    [OUT_ERRORS]: await formatMarkdown(OUT_ERRORS, renderErrorCodes(errors)),
    [OUT_LIMITS]: await formatMarkdown(OUT_LIMITS, renderRateLimits(limits)),
    [OUT_LLMS]: renderLlms(root, errors, limits),
  };
}

async function check(root) {
  const drift = [];
  for (const [rel, content] of Object.entries(await generate(root))) {
    const file = path.join(root, rel);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current !== content) drift.push(rel);
  }
  return drift;
}

function control(root) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'machine-docs-control-'));
  try {
    for (const rel of [
      'app/api',
      'lib/api',
      'lib/rate-limit',
      'lib/auth/rate-limit.ts',
      OUT_ERRORS,
      OUT_LIMITS,
      OUT_LLMS,
    ]) {
      const src = path.join(root, rel);
      if (fs.existsSync(src))
        fs.cpSync(src, path.join(tmp, rel), { recursive: true });
    }
    const runCheck = () =>
      spawnSync(process.execPath, [SCRIPT, '--check', '--root', tmp], {
        encoding: 'utf8',
      });
    const clean = runCheck();
    if (clean.status !== 0) {
      console.error(
        'CONTROL INCONCLUSIVE: --check fails on the unmodified copy; run the generator first.'
      );
      console.error(clean.stdout + clean.stderr);
      return 1;
    }
    const planted = path.join(tmp, 'app/api/__machine_docs_control__/route.ts');
    fs.mkdirSync(path.dirname(planted), { recursive: true });
    fs.writeFileSync(
      planted,
      "import { NextResponse } from 'next/server';\n\nexport async function GET() {\n  return NextResponse.json({ error: 'MACHINE_DOCS_PLANTED_CONTROL', message: 'Planted negative control.' }, { status: 418 });\n}\n"
    );
    const dirty = runCheck();
    if (dirty.status === 1 && /docs\/api\/error-codes\.md/.test(dirty.stderr)) {
      console.log(
        'CONTROL PASS: --check passed on the faithful copy and failed after a new error code was planted.'
      );
      return 0;
    }
    console.error(
      `CONTROL FAIL: --check exited ${dirty.status} after a new error code was planted.`
    );
    console.error(dirty.stdout + dirty.stderr);
    return 1;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

async function main(argv) {
  const rootIdx = argv.indexOf('--root');
  const root = rootIdx === -1 ? DEFAULT_ROOT : path.resolve(argv[rootIdx + 1]);
  if (argv.includes('--control')) return control(root);
  if (argv.includes('--check')) {
    const drift = await check(root);
    if (drift.length) {
      console.error(
        `Machine docs drift: ${drift.join(', ')}. Run: npm run api:machine-docs`
      );
      return 1;
    }
    console.log('Machine docs up to date.');
    return 0;
  }
  for (const [rel, content] of Object.entries(await generate(root))) {
    const file = path.join(root, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT) {
  main(process.argv.slice(2)).then(
    code => {
      process.exitCode = code;
    },
    err => {
      console.error(err instanceof Error ? err.message : err);
      process.exitCode = 1;
    }
  );
}
