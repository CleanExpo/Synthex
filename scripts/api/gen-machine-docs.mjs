#!/usr/bin/env node
/**
 * Machine-contract docs generator (spec M3, P3 unit `llms`).
 *
 * Reads route source with the TypeScript parser and writes, deterministically
 * (no timestamps, sorted output):
 *
 *   docs/api/error-codes.md  every structured error code string returned by
 *                            app/api routes and lib/api helpers, found as
 *                            `error: '<CODE>'` / `code: '<CODE>'` properties
 *                            (or a const holding such a string), with the HTTP
 *                            status read from the enclosing response call.
 *   docs/api/rate-limits.md  every limiter the routes use: lib/rate-limit
 *                            presets, tier-based withRateLimit, inline
 *                            RateLimiter instances, lib/auth/rate-limit
 *                            buckets, and routes that answer 429 through a
 *                            route-local limiter the scan cannot read.
 *   public/llms.txt          the hand-written preamble above the generated
 *                            marker is kept verbatim; the section from the
 *                            marker down is regenerated.
 *
 * Usage:
 *   node scripts/api/gen-machine-docs.mjs            write the files
 *   node scripts/api/gen-machine-docs.mjs --check    exit 1 on drift
 *   node scripts/api/gen-machine-docs.mjs --control  planted negative control:
 *     copy the inputs to a temp dir, require --check to pass on the faithful
 *     copy, plant a new error code, and require --check to fail.
 *   --root <dir>  run against another tree (tests and --control use this).
 */

