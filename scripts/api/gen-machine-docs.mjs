function routeFiles(root) {
  return walk(path.join(root, 'app/api'))
    .filter(f => ROUTE_FILE_RE.test(path.basename(f)))
    .map(f => toPosix(path.relative(root, f)))
    .sort(cmp);
}

function routePath(rel) {
  const segs = rel
    .split('/')
    .slice(1, -1)
    .filter(s => !/^\(.*\)$/.test(s));
  return '/' + segs.join('/');
}

function libApiFiles(root) {
  return walk(path.join(root, 'lib/api'))
    .filter(f => /\.(ts|tsx)$/.test(f) && !/\.d\.ts$/.test(f))
    .map(f => toPosix(path.relative(root, f)))
    .sort(cmp);
}

function namedImports(sf) {
  /** local name -> { imported, module } */
  const map = new Map();
  for (const st of sf.statements) {
    if (!ts.isImportDeclaration(st) || !ts.isStringLiteral(st.moduleSpecifier))
      continue;
    const bindings = st.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;
    for (const el of bindings.elements) {
      map.set(el.name.text, {
        imported: (el.propertyName ?? el.name).text,
        module: st.moduleSpecifier.text,
      });
    }
  }
  return map;
}

