function renderLlms(root, errors, limits) {
  const file = path.join(root, OUT_LLMS);
  let preamble = '# Synthex\n';
  if (fs.existsSync(file)) {
    const text = fs.readFileSync(file, 'utf8');
    const at = text.indexOf(LLMS_MARKER);
    preamble = at === -1 ? text : text.slice(0, at);
  }
  preamble = preamble.replace(/\s*$/, '\n');
  const codeNames = [...errors.codes.keys()].sort(cmp);
  const list = sortedLimiters(limits.limiters);
  const byKind = k => list.filter(l => l.kind === k);
  const lines = [
    LLMS_MARKER,
    '',
    '## Machine contract',
    '',
    `Generated from the route source of ${errors.routeCount} route files under app/api. Paths below are repository paths.`,
    '',
    `- [OpenAPI document](${OPENAPI_PATH}): the generated OpenAPI contract for the routes under /api/.`,
    `- [Error codes](${OUT_ERRORS}): ${codeNames.length} structured error codes, with HTTP status and meaning.`,
    `- [Rate limits](${OUT_LIMITS}): ${list.length} limiters, their limits and windows, and the routes that use them.`,
    '',
    '## Error codes',
    '',
  ];
  for (const code of codeNames) {
    const statuses = [
      ...new Set(
        errors.codes
          .get(code)
          .occurrences.filter(o => o.route)
          .map(o => o.status ?? 'unresolved')
      ),
    ]
      .map(String)
      .sort(cmp);
    lines.push(`- ${code}: HTTP ${statuses.join(', ') || 'unresolved'}`);
  }
  lines.push('', '## Rate limits', '');
  for (const l of [...byKind('preset'), ...byKind('tier')]) {
    lines.push(
      `- ${l.name}: ${l.limit} requests per ${l.window}; ${routesText(l.routes.size)}`
    );
  }
  const buckets = byKind('org/ip bucket');
  const instances = byKind('route instance');
  if (buckets.length)
    lines.push(
      `- checkRateLimit org/IP buckets: ${buckets.length} configurations; see ${OUT_LIMITS}`
    );
  if (instances.length)
    lines.push(
      `- Route-specific RateLimiter instances: ${instances.length}; see ${OUT_LIMITS}`
    );
  if (limits.routeLocal.length)
    lines.push(
      `- Routes that return 429 without a limiter this scan reads: ${limits.routeLocal.length}; see ${OUT_LIMITS}`
    );
  const out = preamble + '\n' + lines.join('\n') + '\n';
  const count = out.split('\n').length - 1;
  if (count > LLMS_MAX_LINES) {
    throw new Error(
      `${OUT_LLMS} would be ${count} lines; the llms.txt index must stay under 200.`
    );
  }
  return out;
}

