const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const toPosix = p => p.split(path.sep).join('/');
const routesText = n => `${n} route${n === 1 ? '' : 's'}`;
const mdCell = s => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function parse(root, rel) {
  const text = fs.readFileSync(path.join(root, rel), 'utf8');
  const kind = rel.endsWith('x')
    ? ts.ScriptKind.TSX
    : rel.endsWith('.js')
      ? ts.ScriptKind.JS
      : ts.ScriptKind.TS;
  return ts.createSourceFile(rel, text, ts.ScriptTarget.Latest, true, kind);
}

function visit(node, fn) {
  fn(node);
  ts.forEachChild(node, child => visit(child, fn));
}

function propName(p) {
  const n = p.name;
  if (!n) return undefined;
  if (ts.isIdentifier(n) || ts.isStringLiteral(n) || ts.isNumericLiteral(n))
    return n.text;
  return undefined;
}

function getProp(obj, name) {
  if (!obj || !ts.isObjectLiteralExpression(obj)) return undefined;
  return obj.properties.find(
    p => ts.isPropertyAssignment(p) && propName(p) === name
  );
}

function lineOf(sf, node) {
  return sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
}

function unwrap(node) {
  let n = node;
  while (
    n &&
    (ts.isParenthesizedExpression(n) ||
      ts.isAsExpression(n) ||
      ts.isSatisfiesExpression?.(n) ||
      ts.isTypeAssertionExpression(n))
  ) {
    n = n.expression;
  }
  return n;
}

/** File-local `const NAME = <initializer>` map. */
function localConsts(sf) {
  const map = new Map();
  visit(sf, n => {
    if (
      ts.isVariableDeclaration(n) &&
      ts.isIdentifier(n.name) &&
      n.initializer &&
      ts.isVariableDeclarationList(n.parent) &&
      n.parent.flags & ts.NodeFlags.Const
    ) {
      map.set(n.name.text, n.initializer);
    }
  });
  return map;
}

/** Evaluate a numeric expression (60_000, 60 * 1000, a local const). Returns undefined if not static. */
function evalNum(node, consts, depth = 0) {
  const n = unwrap(node);
  if (!n || depth > 8) return undefined;
  if (ts.isNumericLiteral(n)) return Number(n.text.replace(/_/g, ''));
  if (ts.isIdentifier(n) && consts.has(n.text))
    return evalNum(consts.get(n.text), consts, depth + 1);
  if (
    ts.isPrefixUnaryExpression(n) &&
    n.operator === ts.SyntaxKind.MinusToken
  ) {
    const v = evalNum(n.operand, consts, depth + 1);
    return v === undefined ? undefined : -v;
  }
  if (ts.isBinaryExpression(n)) {
    const a = evalNum(n.left, consts, depth + 1);
    const b = evalNum(n.right, consts, depth + 1);
    if (a === undefined || b === undefined) return undefined;
    switch (n.operatorToken.kind) {
      case ts.SyntaxKind.AsteriskToken:
        return a * b;
      case ts.SyntaxKind.PlusToken:
        return a + b;
      case ts.SyntaxKind.MinusToken:
        return a - b;
      case ts.SyntaxKind.SlashToken:
        return a / b;
      default:
        return undefined;
    }
  }
  return undefined;
}

function stringOf(node, consts) {
  const n = unwrap(node);
  if (!n) return undefined;
  if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n))
    return n.text;
  if (ts.isIdentifier(n) && consts?.has(n.text))
    return stringOf(consts.get(n.text));
  return undefined;
}

/** Readable text of a message: string literal, or a template with `${…}` holes. */
function messageText(node) {
  const n = unwrap(node);
  if (!n) return undefined;
  if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n))
    return n.text;
  if (ts.isTemplateExpression(n)) {
    return (
      n.head.text + n.templateSpans.map(s => '…' + s.literal.text).join('')
    );
  }
  if (
    ts.isBinaryExpression(n) &&
    n.operatorToken.kind === ts.SyntaxKind.PlusToken
  ) {
    const a = messageText(n.left);
    const b = messageText(n.right);
    if (a !== undefined || b !== undefined) return (a ?? '…') + (b ?? '…');
  }
  return undefined;
}

/** First sentence of the leading JSDoc on a node. */
function leadingDoc(sf, node) {
  const ranges = ts.getLeadingCommentRanges(sf.text, node.getFullStart()) ?? [];
  const doc = ranges
    .filter(r => sf.text.slice(r.pos, r.pos + 3) === '/**')
    .pop();
  if (!doc) return undefined;
  const body = sf.text
    .slice(doc.pos + 3, doc.end - 2)
    .split('\n')
    .map(l => l.replace(/^\s*\*\s?/, '').trim())
    .filter(Boolean)
    .join(' ');
  const m = body.match(/^(.*?[.!?])(\s|$)/);
  return (m ? m[1] : body).trim() || undefined;
}

function formatWindow(ms) {
  if (ms === undefined) return 'unresolved';
  const s = ms / 1000;
  if (s >= 3600 && s % 3600 === 0) return `${s} s (${s / 3600} h)`;
  return `${s} s`;
}

/**
 * HTTP status for a response body node: climb through enclosing object
 * literals until the node is the first argument of a call, then read that
 * call's second argument (a number, or an object with a numeric `status`).
 */
function statusFor(node, consts) {
  let n = node;
  for (let i = 0; i < 8 && n; i++) {
    const p = n.parent;
    if (!p) return undefined;
    if (ts.isCallExpression(p) || ts.isNewExpression(p)) {
      const args = p.arguments ?? [];
      if (args[0] !== n) return undefined;
      const second = unwrap(args[1]);
      if (!second) return undefined;
      const direct = evalNum(second, consts);
      if (direct !== undefined) return direct;
      const st = getProp(second, 'status');
      return st ? evalNum(st.initializer, consts) : undefined;
    }
    if (
      ts.isObjectLiteralExpression(p) ||
      ts.isPropertyAssignment(p) ||
      ts.isSpreadAssignment(p) ||
      ts.isParenthesizedExpression(p) ||
      ts.isAsExpression(p) ||
      ts.isSatisfiesExpression?.(p)
    ) {
      n = p;
      continue;
    }
    return undefined;
  }
  return undefined;
}

