function collectErrorCodes(root) {
  const routes = routeFiles(root);
  const libs = libApiFiles(root);
  /** code -> { occurrences: [{ file, line, route, status, message, via }], meaning } */
  const codes = new Map();
  const add = (code, occ) => {
    if (!codes.has(code))
      codes.set(code, { occurrences: [], meaning: undefined });
    codes.get(code).occurrences.push(occ);
  };

  // lib/api: exported code constants (with doc) and helper functions that emit codes.
  const libConstDoc = new Map(); // code value -> meaning from doc
  const libConstNames = new Map(); // const name -> code value
  const helpers = new Map(); // function name -> [{ code, status }]
  const libNumConsts = new Map(); // '@/lib/api/<module>' -> Map(const name -> number)
  const parsedLibs = libs.map(rel => [rel, parse(root, rel)]);
  for (const [rel, sf] of parsedLibs) {
    const consts = localConsts(sf);
    const nums = new Map();
    libNumConsts.set('@/' + rel.replace(/(\/index)?\.tsx?$/, ''), nums);
    const fileDoc = sf.statements.length
      ? leadingDoc(sf, sf.statements[0])
      : undefined;
    for (const st of sf.statements) {
      if (!ts.isVariableStatement(st)) continue;
      for (const d of st.declarationList.declarations) {
        if (!ts.isIdentifier(d.name)) continue;
        const num = evalNum(d.initializer, consts);
        if (num !== undefined) nums.set(d.name.text, num);
        const v = stringOf(d.initializer, consts);
        if (v && CODE_RE.test(v) && d.name.text === v) {
          libConstNames.set(d.name.text, v);
          libConstDoc.set(v, leadingDoc(sf, st) ?? fileDoc);
        }
      }
    }
  }

  const scanFile = (rel, sf, isRoute) => {
    const consts = localConsts(sf);
    for (const [name, v] of libConstNames)
      if (!consts.has(name))
        consts.set(name, ts.factory.createStringLiteral(v));
    const imports = namedImports(sf);
    // Numeric consts imported from lib/api (e.g. NOT_PROVISIONED_STATUS) resolve a status.
    for (const [local, { imported, module }] of imports) {
      const num = libNumConsts.get(module)?.get(imported);
      if (num !== undefined && !consts.has(local))
        consts.set(local, ts.factory.createNumericLiteral(num));
    }
    visit(sf, n => {
      if (
        ts.isPropertyAssignment(n) &&
        ['error', 'code'].includes(propName(n))
      ) {
        const code = stringOf(n.initializer, consts);
        if (!code || !CODE_RE.test(code)) return;
        const obj = n.parent;
        const msgProp =
          getProp(obj, 'message') ??
          (propName(n) === 'code' ? getProp(obj, 'error') : undefined);
        const occ = {
          file: rel,
          line: lineOf(sf, n),
          route: isRoute ? routePath(rel) : undefined,
          status: statusFor(obj, consts),
          message: msgProp ? messageText(msgProp.initializer) : undefined,
        };
        if (!isRoute) {
          let fn = n.parent;
          while (fn && !ts.isFunctionDeclaration(fn)) fn = fn.parent;
          occ.helper = fn?.name?.text;
          if (occ.helper) {
            if (!helpers.has(occ.helper)) helpers.set(occ.helper, []);
            helpers.get(occ.helper).push({ code, status: occ.status });
          }
        }
        add(code, occ);
      }
      // Route call sites of lib/api helpers that emit a code.
      if (
        isRoute &&
        ts.isCallExpression(n) &&
        ts.isIdentifier(n.expression) &&
        helpers.has(n.expression.text) &&
        imports.get(n.expression.text)?.module.startsWith('@/lib/api/')
      ) {
        for (const h of helpers.get(n.expression.text)) {
          add(h.code, {
            file: rel,
            line: lineOf(sf, n),
            route: routePath(rel),
            status: h.status ?? statusFor(n, consts),
            message: undefined,
            via: n.expression.text,
          });
        }
      }
    });
  };

  for (const [rel, sf] of parsedLibs) scanFile(rel, sf, false);
  for (const rel of routes) scanFile(rel, parse(root, rel), true);

  for (const [code, entry] of codes) {
    entry.occurrences.sort((a, b) => cmp(a.file, b.file) || a.line - b.line);
    const firstMsg =
      entry.occurrences.find(o => o.message && o.route)?.message ??
      entry.occurrences.find(o => o.message)?.message;
    entry.meaning = libConstDoc.get(code) ?? firstMsg;
  }
  return { codes, routeCount: routes.length };
}

function renderErrorCodes({ codes }) {
  const names = [...codes.keys()].sort(cmp);
  const lines = [
    '# API error codes',
    '',
    GENERATED_NOTE,
    '',
    "Scope: every `app/api/**/route.{ts,tsx,js}` file and every `lib/api/**` helper. A code is a SCREAMING_SNAKE string (or a `const` holding one) set as the `error` or `code` property of a response body. HTTP status is read from the enclosing response call (`NextResponse.json(body, { status })` or a numeric second argument); when it is not a literal there, it is listed as unresolved rather than guessed. Meaning comes from the defining helper's doc comment, else the first `message` beside the code in source.",
    '',
    `${names.length} codes.`,
    '',
    '| Code | HTTP status | Meaning | Routes |',
    '| ---- | ----------- | ------- | ------ |',
  ];
  const unresolved = [];
  for (const code of names) {
    const { occurrences, meaning } = codes.get(code);
    const statuses = [
      ...new Set(
        occurrences
          .filter(o => o.route || o.status !== undefined)
          .map(o => o.status)
      ),
    ];
    const known = statuses.filter(s => s !== undefined).sort((a, b) => a - b);
    const statusText =
      [
        ...known.map(String),
        ...(statuses.includes(undefined) ? ['unresolved'] : []),
      ].join(', ') || 'unresolved';
    if (statuses.includes(undefined) || !known.length) unresolved.push(code);
    const routes = [
      ...new Set(occurrences.filter(o => o.route).map(o => o.route)),
    ].sort(cmp);
    lines.push(
      `| \`${code}\` | ${statusText} | ${mdCell(meaning ?? '(no message in source)')} | ${routes.length ? routes.map(r => `\`${r}\``).join(', ') : '(lib/api helper only)'} |`
    );
  }
  // Files, not line numbers: a line number in a committed doc goes stale on any edit above it, and
  // the CI drift check would then fail unrelated PRs. Repeats within a file collapse to one entry.
  const uniq = xs => [...new Set(xs)];
  lines.push('', '## Codes with an unresolved HTTP status', '');
  if (!unresolved.length) lines.push('None.');
  for (const code of unresolved) {
    // A lib/api helper that returns only a body gets its status at each call site.
    const occ = codes
      .get(code)
      .occurrences.filter(o => o.status === undefined && o.route);
    lines.push(
      `- \`${code}\`: ${uniq(occ.map(o => `${o.file}${o.via ? ` (via ${o.via})` : ''}`)).join(', ')}`
    );
  }
  lines.push('', '## Source locations', '');
  for (const code of names) {
    const occ = codes.get(code).occurrences;
    lines.push(
      `- \`${code}\`: ${uniq(occ.map(o => `${o.file}${o.status !== undefined ? ` (${o.status})` : ''}${o.via ? ` via ${o.via}` : ''}`)).join(', ')}`
    );
  }
  return lines.join('\n') + '\n';
}

