function readPresets(root) {
  const rel = 'lib/rate-limit/presets.ts';
  const presets = new Map(); // export name -> { category, windowMs, maxRequests }
  const aliases = new Map(); // rateLimiters.<key> -> preset export name
  if (!fs.existsSync(path.join(root, rel))) return { presets, aliases };
  const sf = parse(root, rel);
  const consts = localConsts(sf);
  for (const st of sf.statements) {
    if (!ts.isVariableStatement(st)) continue;
    for (const d of st.declarationList.declarations) {
      if (!ts.isIdentifier(d.name) || !d.initializer) continue;
      const init = unwrap(d.initializer);
      if (
        ts.isCallExpression(init) &&
        ts.isIdentifier(init.expression) &&
        init.expression.text === 'createCategoryLimiter'
      ) {
        const [cat, win, max] = init.arguments;
        presets.set(d.name.text, {
          category: stringOf(cat, consts) ?? 'unresolved',
          windowMs: evalNum(win, consts),
          maxRequests: evalNum(max, consts),
        });
      }
      if (
        d.name.text === 'rateLimiters' &&
        ts.isObjectLiteralExpression(init)
      ) {
        for (const p of init.properties) {
          if (ts.isPropertyAssignment(p) && ts.isIdentifier(p.initializer))
            aliases.set(propName(p), p.initializer.text);
        }
      }
    }
  }
  return { presets, aliases };
}

function readTiers(root) {
  const rel = 'lib/rate-limit/rate-limiter.ts';
  const out = { defaults: [], endpoints: new Map(), windowMs: undefined };
  if (!fs.existsSync(path.join(root, rel))) return out;
  const sf = parse(root, rel);
  const consts = localConsts(sf);
  const tierList = obj =>
    unwrap(obj)
      ?.properties?.filter(p => ts.isPropertyAssignment(p))
      .map(p => [propName(p), evalNum(p.initializer, consts)]) ?? [];
  if (consts.has('DEFAULT_TIER_LIMITS'))
    out.defaults = tierList(consts.get('DEFAULT_TIER_LIMITS'));
  const ep = unwrap(consts.get('ENDPOINT_LIMITS'));
  if (ep && ts.isObjectLiteralExpression(ep)) {
    for (const p of ep.properties)
      if (ts.isPropertyAssignment(p))
        out.endpoints.set(propName(p), tierList(p.initializer));
  }
  visit(sf, n => {
    if (ts.isFunctionDeclaration(n) && n.name?.text === 'createRateLimiter') {
      visit(n, m => {
        if (
          ts.isNewExpression(m) &&
          ts.isIdentifier(m.expression) &&
          m.expression.text === 'RateLimiter'
        ) {
          const w = getProp(unwrap(m.arguments?.[0]), 'windowMs');
          if (w) out.windowMs = evalNum(w.initializer, consts);
        }
      });
    }
  });
  return out;
}

function readAuthBuckets(root) {
  const rel = 'lib/auth/rate-limit.ts';
  const out = {};
  if (!fs.existsSync(path.join(root, rel))) return out;
  const sf = parse(root, rel);
  const consts = localConsts(sf);
  for (const [key, name] of [
    ['org', 'DEFAULT_ORG_LIMIT'],
    ['ip', 'DEFAULT_IP_LIMIT'],
  ]) {
    const obj = unwrap(consts.get(name));
    const limit = getProp(obj, 'limit');
    const win = getProp(obj, 'windowSeconds');
    out[key] = {
      limit: limit ? evalNum(limit.initializer, consts) : undefined,
      windowMs: win ? evalNum(win.initializer, consts) * 1000 : undefined,
    };
  }
  return out;
}

const tierText = list =>
  list.map(([t, v]) => `${t} ${v ?? 'unresolved'}`).join(', ');

function collectRateLimits(root) {
  const { presets, aliases } = readPresets(root);
  const tiers = readTiers(root);
  const auth = readAuthBuckets(root);
  /** limiter key -> { name, kind, limit, window, routes:Set } */
  const limiters = new Map();
  const use = (key, def, route) => {
    if (!limiters.has(key)) limiters.set(key, { ...def, routes: new Set() });
    limiters.get(key).routes.add(route);
  };
  const routeLocal = [];

  for (const rel of routeFiles(root)) {
    const sf = parse(root, rel);
    const consts = localConsts(sf);
    const imports = namedImports(sf);
    const route = routePath(rel);
    let found = false;
    let has429 = false;
    visit(sf, n => {
      if (ts.isNumericLiteral(n) && n.text === '429') has429 = true;
      if (ts.isCallExpression(n)) {
        const callee = n.expression;
        // Preset wrappers (direct or aliased import) and legacy rateLimiters.<key>.
        let preset;
        if (ts.isIdentifier(callee)) {
          const imp = imports.get(callee.text);
          if (
            imp &&
            PRESET_MODULES.has(imp.module) &&
            presets.has(imp.imported)
          )
            preset = imp.imported;
          if (
            imp &&
            TIER_MODULES.has(imp.module) &&
            imp.imported === 'withRateLimit'
          ) {
            found = true;
            const ep = tiers.endpoints.get(route);
            use(
              ep ? `withRateLimit ${route}` : 'withRateLimit',
              {
                name: ep
                  ? `withRateLimit (${route} override)`
                  : 'withRateLimit (tier default)',
                kind: 'tier',
                limit: tierText(ep ?? tiers.defaults),
                window: formatWindow(tiers.windowMs),
              },
              route
            );
          }
          if (
            imp &&
            imp.module === AUTH_LIMIT_MODULE &&
            imp.imported === 'checkRateLimit'
          ) {
            found = true;
            const opts = unwrap(n.arguments[1]);
            const ns =
              stringOf(getProp(opts, 'namespace')?.initializer, consts) ??
              'unresolved';
            const limits = unwrap(getProp(opts, 'limits')?.initializer);
            for (const bucket of ['org', 'ip']) {
              const custom = unwrap(getProp(limits, bucket)?.initializer);
              const l = custom
                ? evalNum(getProp(custom, 'limit')?.initializer, consts)
                : auth[bucket]?.limit;
              const w = custom
                ? (evalNum(
                    getProp(custom, 'windowSeconds')?.initializer,
                    consts
                  ) ?? NaN) * 1000
                : auth[bucket]?.windowMs;
              const win = Number.isFinite(w) ? w : undefined;
              use(
                `checkRateLimit ${ns} ${bucket} ${l} ${win}`,
                {
                  name: `checkRateLimit '${ns}' (${bucket} bucket${custom ? '' : ', default'})`,
                  kind: 'org/ip bucket',
                  limit: l ?? 'unresolved',
                  window: formatWindow(win),
                },
                route
              );
            }
          }
        } else if (
          ts.isPropertyAccessExpression(callee) &&
          ts.isIdentifier(callee.expression) &&
          PRESET_MODULES.has(imports.get(callee.expression.text)?.module) &&
          imports.get(callee.expression.text)?.imported === 'rateLimiters'
        ) {
          preset = aliases.get(callee.name.text);
        }
        if (preset) {
          found = true;
          const p = presets.get(preset);
          use(
            `preset ${preset}`,
            {
              name: `${preset} ('${p.category}')`,
              kind: 'preset',
              limit: p.maxRequests ?? 'unresolved',
              window: formatWindow(p.windowMs),
            },
            route
          );
        }
      }
      if (
        ts.isNewExpression(n) &&
        ts.isIdentifier(n.expression) &&
        n.expression.text === 'RateLimiter' &&
        imports.get('RateLimiter')
      ) {
        found = true;
        const cfg = unwrap(n.arguments?.[0]);
        const winProp = getProp(cfg, 'windowMs');
        const maxProp = getProp(cfg, 'maxRequests');
        const win = winProp ? evalNum(winProp.initializer, consts) : undefined;
        const max = maxProp ? evalNum(maxProp.initializer, consts) : undefined;
        const v =
          n.parent &&
          ts.isVariableDeclaration(n.parent) &&
          ts.isIdentifier(n.parent.name)
            ? n.parent.name.text
            : 'inline';
        use(
          `RateLimiter ${route} ${v} ${lineOf(sf, n)}`,
          {
            // File only: a committed line number goes stale on any edit above it.
            name: `RateLimiter \`${v}\` (${rel})`,
            kind: 'route instance',
            limit:
              max ??
              `unresolved (\`${maxProp?.initializer.getText(sf) ?? 'missing'}\`)`,
            window:
              win !== undefined
                ? formatWindow(win)
                : `unresolved (\`${winProp?.initializer.getText(sf) ?? 'missing'}\`)`,
          },
          route
        );
      }
    });
    if (!found && has429) routeLocal.push(rel);
  }
  const unusedOverrides = [...tiers.endpoints.keys()]
    .filter(k => !limiters.has(`withRateLimit ${k}`))
    .sort(cmp);
  return { limiters, routeLocal, presets, tiers, unusedOverrides };
}

const KIND_ORDER = ['preset', 'tier', 'org/ip bucket', 'route instance'];

function sortedLimiters(limiters) {
  return [...limiters.values()].sort(
    (a, b) =>
      KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind) ||
      cmp(a.name, b.name)
  );
}

function renderRateLimits({
  limiters,
  routeLocal,
  presets,
  tiers,
  unusedOverrides,
}) {
  const list = sortedLimiters(limiters);
  const routes = new Set(list.flatMap(l => [...l.routes]));
  const lines = [
    '# API rate limits',
    '',
    GENERATED_NOTE,
    '',
    'Scope: limiters called from `app/api/**/route.{ts,tsx,js}` — the category presets in `lib/rate-limit/presets.ts` (also reached through `lib/middleware/api-rate-limit` and the legacy `rateLimiters` map), the subscription-tier `withRateLimit` in `lib/rate-limit/rate-limiter.ts`, `new RateLimiter({ windowMs, maxRequests })` instances in route files, and `checkRateLimit` org/IP buckets in `lib/auth/rate-limit.ts`. Values are read from source; a value that is not a static expression is listed as unresolved.',
    '',
    `${list.length} limiters across ${routesText(routes.size)}.`,
    '',
    '| Limiter | Kind | Limit (requests) | Window | Routes |',
    '| ------- | ---- | ---------------- | ------ | ------ |',
  ];
  for (const l of list) {
    lines.push(
      `| ${mdCell(l.name)} | ${l.kind} | ${mdCell(l.limit)} | ${mdCell(l.window)} | ${l.routes.size} |`
    );
  }
  lines.push('', '## Preset definitions', '');
  for (const [name, p] of [...presets].sort((a, b) => cmp(a[0], b[0]))) {
    const n = limiters.get(`preset ${name}`)?.routes.size ?? 0;
    lines.push(
      `- \`${name}\` ('${p.category}'): ${p.maxRequests ?? 'unresolved'} requests per ${formatWindow(p.windowMs)}; ${routesText(n)}.`
    );
  }
  lines.push(
    '',
    '## Tier limits (`withRateLimit`)',
    '',
    `Window ${formatWindow(tiers.windowMs)}. Default per tier: ${tierText(tiers.defaults) || 'unresolved'}.`,
    ''
  );
  for (const [ep, t] of [...tiers.endpoints].sort((a, b) => cmp(a[0], b[0]))) {
    lines.push(`- Override for \`${ep}\`: ${tierText(t)}.`);
  }
  if (unusedOverrides.length) {
    lines.push(
      '',
      'Overrides with no matching `withRateLimit` route file (they never apply): ' +
        unusedOverrides.map(e => `\`${e}\``).join(', ') +
        '.'
    );
  }
  lines.push('', '## Routes per limiter', '');
  for (const l of list) {
    lines.push(
      `### ${l.name}`,
      '',
      [...l.routes]
        .sort(cmp)
        .map(r => `- \`${r}\``)
        .join('\n'),
      ''
    );
  }
  lines.push('## Route-local limiters not read by this scan', '');
  if (!routeLocal.length) lines.push('None.');
  else {
    lines.push(
      'These route files contain a 429 status but call none of the limiters above. The 429 may come from a hand-rolled counter, a limiter this scan does not recognise, or a forwarded upstream status. Their limits are not stated here.',
      ''
    );
    for (const rel of routeLocal)
      lines.push(`- \`${routePath(rel)}\` (${rel})`);
  }
  return lines.join('\n') + '\n';
}

